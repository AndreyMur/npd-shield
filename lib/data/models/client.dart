import 'package:isar/isar.dart';

import '../../domain/documents/my_tax_deep_link.dart';

part 'client.g.dart';

/// Карточка контрагента из справочника клиентов.
///
/// Справочник ведёт пользователь: клиент создаётся, редактируется и удаляется
/// вручную. Строковые поля (наименование, ИНН, контакты, заметки) шифруются на
/// уровне поля (AES-256), поэтому не индексируются: поиск по справочнику
/// выполняется в памяти после расшифровки.
///
/// Тип клиента ([type]) совпадает с типом покупателя для чека «Мой налог»
/// ([ClientType]) и определяет вид дохода в deep link.
///
/// Удаление клиента не затрагивает связанные операции и документы: связь
/// хранится как идентификатор (`Transaction.clientId`, `Document.clientId`) и
/// после удаления карточки остаётся в записях истории.
@collection
class Client {
  Id id = Isar.autoIncrement;

  /// Наименование организации или ФИО. Шифруется при хранении.
  String name;

  /// ИНН клиента (10 цифр для юрлица, 12 — для физлица). Шифруется.
  String inn;

  /// Тип клиента: юрлицо/ИП или физлицо.
  @enumerated
  ClientType type;

  /// Контакты клиента: телефон, почта, контактное лицо. Шифруется.
  String contacts;

  /// Произвольные заметки пользователя о клиенте. Шифруются.
  String notes;

  /// Дата создания карточки в базе.
  @Index()
  DateTime createdAt = DateTime.now();

  Client({
    required this.name,
    this.inn = '',
    this.type = ClientType.individual,
    this.contacts = '',
    this.notes = '',
  });
}

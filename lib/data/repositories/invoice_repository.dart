import '../models/invoice.dart';
import '../models/transaction.dart';

/// Хранилище счетов на оплату.
///
/// Помимо CRUD репозиторий отвечает за жизненный цикл счёта: отметку оплаты
/// (в том числе частичной) с созданием дохода-операции и выборку просроченных
/// счетов. Просрочка не хранится в базе, а вычисляется по сроку оплаты и
/// текущей дате ([Invoice.effectiveStatus]), поэтому статус «просрочен»
/// невозможно выставить вручную.
abstract class InvoiceRepository {
  /// Сохраняет новый счёт и возвращает его `id`.
  ///
  /// Бросает [ArgumentError], если у счёта выставлен статус «просрочен»:
  /// этот статус вычисляется автоматически.
  Future<int> add(Invoice invoice);

  /// Возвращает счёт по идентификатору или `null`.
  Future<Invoice?> getById(int id);

  /// Сохраняет изменения счёта и возвращает его `id`.
  ///
  /// Бросает [ArgumentError], если у счёта выставлен статус «просрочен».
  Future<int> update(Invoice invoice);

  /// Удаляет счёт по идентификатору. Созданный при оплате доход не удаляется.
  Future<bool> delete(int id);

  /// Количество счетов.
  Future<int> count();

  /// Возвращает все счета, самые новые (по дате выставления) — первыми.
  Future<List<Invoice>> getAll();

  /// Возвращает счета, привязанные к карточке клиента.
  Future<List<Invoice>> getByClientId(int clientId);

  /// Возвращает просроченные счета (по [now], по умолчанию — сейчас),
  /// самые старые по сроку оплаты — первыми.
  Future<List<Invoice>> getOverdue({DateTime? now});

  /// Суммарная дебиторская задолженность: остаток к оплате по всем
  /// выставленным (не черновикам и не отменённым) счетам.
  Future<double> getOutstandingTotal({DateTime? now});

  /// Отмечает оплату счёта.
  ///
  /// [amount] — сумма платежа; если не задана, гасится весь остаток. Частичная
  /// оплата накапливается в [Invoice.paidAmount]. При полной оплате счёт
  /// переводится в статус «оплачен» и создаётся доход-операция с суммой счёта.
  /// Повторная оплата полностью оплаченного счёта ничего не меняет.
  Future<Invoice> markPaid(
    int id, {
    double? amount,
    DateTime? paidAt,
    TransactionSphere sphere = TransactionSphere.it,
    String category = '',
    String comment = '',
  });

  /// Удаляет все счета (используется при полной очистке данных).
  Future<void> clear();
}
